using System.Text;

namespace LocalBoost;

/// <summary>
/// 生成 PAC（Proxy Auto-Config）脚本。
///
/// 只把规则表里的域名指向本地代理，其余按调用方给的兜底指令走 ——
/// 不能无脑 DIRECT：用户本来可能配着系统代理，那样会把没接管的流量
/// 从"走代理"悄悄变成"直连"。
/// </summary>
public static class PacScript
{
    public static string Build(RuleBook rules, int proxyPort, string fallbackDirective = "DIRECT")
    {
        var exact = new SortedSet<string>(StringComparer.OrdinalIgnoreCase);
        var suffixes = new SortedSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var host in rules.EnabledHosts())
        {
            if (host.StartsWith("*.", StringComparison.Ordinal))
                suffixes.Add(host[2..]);
            else
                exact.Add(host);
        }

        var sb = new StringBuilder();

        // 注释刻意只写 ASCII：PAC 由 WinINET 的脚本引擎解析，文件里出现非 ASCII
        // 字节时读法取决于系统代码页，注释里的中文字节有可能被误解成奇怪的东西。
        // 生成物只求绝对安全，说明文字放在代码和日志里。
        sb.AppendLine("// Generated by LocalBoost. Rewritten on every start - do not edit.");
        sb.AppendLine("// Only hosts from the rule table go through the local proxy.");
        sb.AppendLine("function FindProxyForURL(url, host) {");
        sb.AppendLine("  host = host.toLowerCase();");
        sb.AppendLine($"  var proxy = \"PROXY 127.0.0.1:{proxyPort}\";");
        sb.AppendLine();

        // 域名都经过 RuleBook.IsValidHostName 校验（只允许字母数字、连字符与点），
        // 所以拼进 JS 字符串里不会引入注入。
        foreach (var host in exact)
            sb.AppendLine($"  if (host === \"{host}\") return proxy;");

        if (exact.Count > 0 && suffixes.Count > 0)
            sb.AppendLine();

        foreach (var suffix in suffixes)
        {
            // dnsDomainIs 要求带前导点，正好和规则里 "*.example.com" 的语义
            // （只匹配子域、不匹配裸域）一致，也不会误命中 evilgithub.io。
            sb.AppendLine($"  if (dnsDomainIs(host, \".{suffix}\")) return proxy;");
        }

        sb.AppendLine();
        sb.AppendLine($"  return \"{fallbackDirective}\";");
        sb.AppendLine("}");
        return sb.ToString();
    }
}
